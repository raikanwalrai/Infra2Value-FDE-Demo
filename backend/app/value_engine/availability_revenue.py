from .models import (
    AvailabilityRevenueInput,
    AvailabilityRevenueResult,
)


def calculate_availability_revenue(
    inputs: AvailabilityRevenueInput,
) -> AvailabilityRevenueResult:
    """
    Calculate incremental revenue generated by recovering
    otherwise lost transactions.

    Deterministic calculation:

        recovered_transactions =
            affected_transactions_per_month * recovery_rate

        incremental_revenue_per_month =
            recovered_transactions * average_transaction_value

        incremental_revenue_per_year =
            incremental_revenue_per_month * months_per_year
    """

    recovered_transactions = (
        inputs.affected_transactions_per_month
        * inputs.recovery_rate
    )

    incremental_revenue_per_month = (
        recovered_transactions
        * inputs.average_transaction_value
    )

    incremental_revenue_per_year = (
        incremental_revenue_per_month
        * inputs.months_per_year
    )

    return AvailabilityRevenueResult(
        affected_transactions_per_month=(
            inputs.affected_transactions_per_month
        ),
        recovery_rate=inputs.recovery_rate,
        recovered_transactions_per_month=recovered_transactions,
        average_transaction_value=(
            inputs.average_transaction_value
        ),
        incremental_revenue_per_month=(
            incremental_revenue_per_month
        ),
        incremental_revenue_per_year=(
            incremental_revenue_per_year
        ),
        months_per_year=inputs.months_per_year,
    )
